"""Generate a small, valid OpenH-4D submission for tests and examples.

The volumes contain a sphere that moves on a closed loop across the time axis.
That matters: a generator that emitted noise or a static shape would let the
motion checks pass vacuously, and the motion checks are the part of the pipeline
unique to a 4D initiative.

Everything is tiny by default -- 24x24x12 int16 voxels, ten time points, two
patients -- so the whole generate, verify, convert chain runs in seconds and can
sit in the per-pull-request CI job.

Usage::

    python -m openh4d.synthetic --out <dir>
    python -m openh4d.synthetic --out <dir> --form dicom_phases
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np

from . import naming

DEFAULT_PREFIX = "OH4D"
DEFAULT_SHAPE = (24, 24, 12)
DEFAULT_TIMEPOINTS = 10
DEFAULT_IN_PLANE_MM = (0.8, 0.8)
DEFAULT_SLICE_SPACING_MM = 1.0

#: Two patients; the first contributed two studies, so the letter-suffix rule is
#: exercised by the default fixture rather than only by a special case.
DEFAULT_PLAN = [
    ("heart", "cardiac", 2),
    ("lung", "respiratory", 1),
]

CC_BY_NOTICE = """\
This dataset is licensed under the Creative Commons Attribution 4.0
International License (CC BY 4.0).

    https://creativecommons.org/licenses/by/4.0/

This is synthetic data generated by openh4d.synthetic for testing. It contains
no patient information of any kind.
"""


def moving_sphere(
    shape: tuple[int, int, int], n_timepoints: int, *, amplitude: float = 0.25
) -> np.ndarray:
    """A sphere translating on a closed loop, as ``(n_timepoints, *shape)`` int16.

    The loop closes so the last time point flows back into the first, the way a
    cardiac or respiratory cycle does.
    """
    nx, ny, nz = shape
    grid = np.stack(
        np.meshgrid(np.arange(nx), np.arange(ny), np.arange(nz), indexing="ij"), axis=-1
    ).astype(np.float64)

    centre = np.array([nx / 2, ny / 2, nz / 2])
    radius = min(shape) * 0.28
    travel = np.array([nx, ny, nz]) * amplitude

    volumes = np.empty((n_timepoints, *shape), dtype=np.int16)
    for index in range(n_timepoints):
        angle = 2 * np.pi * index / n_timepoints
        offset = travel * np.array([np.sin(angle), np.cos(angle), 0.0]) * 0.5
        distance = np.linalg.norm(grid - (centre + offset), axis=-1)
        # A soft edge keeps the intensity curve smooth, which is what the motion
        # report measures; a hard binary edge would quantize it.
        volumes[index] = np.clip(1000 * (1.0 - distance / radius), 0, 1000).astype(np.int16)
    return volumes


def _affine(in_plane_mm: tuple[float, float], slice_spacing_mm: float) -> np.ndarray:
    affine = np.eye(4)
    affine[0, 0] = in_plane_mm[0]
    affine[1, 1] = in_plane_mm[1]
    affine[2, 2] = slice_spacing_mm
    return affine


def _study_json(
    study_id: str,
    patient_id: str,
    organ: str,
    motion: str,
    file_layout: str,
    volumes: np.ndarray,
    in_plane_mm: tuple[float, float],
    slice_spacing_mm: float,
    *,
    derived_from_dicom: bool = False,
) -> dict[str, Any]:
    n_timepoints = int(volumes.shape[0])
    shape = tuple(int(n) for n in volumes.shape[1:])
    phase_type = "cardiac" if motion == "cardiac" else "respiratory"

    if file_layout == "single_4d":
        files = ["image4d.nii.gz"] * n_timepoints
    elif file_layout == "dicom_phases" and not derived_from_dicom:
        files = [f"dicom/t{i:04d}" for i in range(n_timepoints)]
    else:
        files = [f"t{i:04d}.nii.gz" for i in range(n_timepoints)]

    study: dict[str, Any] = {
        "schema": "openh-4d/study/1.0",
        "study_id": study_id,
        "patient_id": patient_id,
        "modality": "CT",
        "organ": organ,
        "motion": motion,
        "protocol": f"Synthetic 4D CT ({motion} motion)",
        "clinical_indication": "synthetic test fixture",
        "file_layout": file_layout,
        "n_timepoints": n_timepoints,
        "timepoints": [
            {
                "index": i,
                "file": files[i],
                "phase_label": f"{i * 100 // n_timepoints}%",
                "phase_type": phase_type,
                "phase_fraction": round(i / n_timepoints, 4),
                "trigger_time_ms": None,
                "acquisition_time_s": None,
            }
            for i in range(n_timepoints)
        ],
        "coverage": "full",
        "coverage_notes": "",
        "contrast": {"used": False, "agent": None, "phase": None},
        "geometry": {
            "in_plane_mm": [in_plane_mm[0], in_plane_mm[1]],
            "slice_spacing_mm": slice_spacing_mm,
            "matrix": list(shape),
            "temporal_resolution_ms": 100,
            "orientation": "RAS",
        },
        "ct": {"low_dose": False, "kvp": 120, "exposure_mas": 150, "recon_kernel": "synthetic"},
        "gating": {
            "method": "retrospective_ecg" if motion == "cardiac" else "respiratory_belt",
            "phase_source": "synthetic",
        },
        "annotations": {"segmentations": [], "landmarks": [], "categorizations": []},
        "derived": [],
        "source": {
            "original_format": "synthetic",
            "converter": "openh4d.synthetic",
            "converter_args": None,
            "converted_at": None,
            "n_source_files": 0,
        },
        "waivers": [],
        "notes": "Synthetic fixture generated by openh4d.synthetic. Not real patient data.",
    }
    if derived_from_dicom:
        study["derived_from_dicom"] = True
    return study


